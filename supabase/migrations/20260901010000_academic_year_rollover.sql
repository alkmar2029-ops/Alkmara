-- Safe academic-year rollover.
-- Keeps operational history intact, snapshots every student's grade/section
-- per year, and replaces the legacy in-place-only promotion workflow.

CREATE TABLE IF NOT EXISTS public.academic_years (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(20) NOT NULL UNIQUE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned', 'open', 'closed', 'cancelled')),
  opened_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT academic_year_dates_valid CHECK (end_date > start_date)
);

CREATE UNIQUE INDEX IF NOT EXISTS academic_years_one_open_idx
  ON public.academic_years ((status)) WHERE status = 'open';

ALTER TABLE public.school_settings
  ADD COLUMN IF NOT EXISTS academic_year_id BIGINT
  REFERENCES public.academic_years(id) ON DELETE RESTRICT;

-- Backfill the existing settings label as the first open year. The dates are
-- metadata defaults only; administrators choose exact dates for future years.
WITH current_settings AS (
  SELECT
    COALESCE(NULLIF(trim(academic_year), ''),
      extract(year FROM current_date)::INT::TEXT || '-' ||
      (extract(year FROM current_date)::INT + 1)::TEXT) AS year_name
  FROM public.school_settings
  WHERE id = 1
), normalized AS (
  SELECT
    year_name,
    CASE WHEN year_name ~ '^\d{4}-\d{4}$'
      THEN make_date(left(year_name, 4)::INT, 8, 1)
      ELSE current_date
    END AS starts_on,
    CASE WHEN year_name ~ '^\d{4}-\d{4}$'
      THEN make_date(right(year_name, 4)::INT, 7, 31)
      ELSE current_date + 365
    END AS ends_on
  FROM current_settings
)
INSERT INTO public.academic_years (name, start_date, end_date, status, opened_at)
SELECT year_name, starts_on, ends_on, 'open', now()
FROM normalized
ON CONFLICT (name) DO UPDATE
SET status = CASE
      WHEN public.academic_years.status IN ('planned', 'cancelled') THEN 'open'
      ELSE public.academic_years.status
    END,
    opened_at = COALESCE(public.academic_years.opened_at, now()),
    updated_at = now();

UPDATE public.school_settings ss
SET academic_year_id = ay.id,
    academic_year = ay.name,
    updated_at = now()
FROM public.academic_years ay
WHERE ss.id = 1
  AND ay.name = COALESCE(NULLIF(trim(ss.academic_year), ''), ay.name)
  AND ay.status = 'open'
  AND ss.academic_year_id IS NULL;

CREATE TABLE IF NOT EXISTS public.student_academic_year_enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year_id BIGINT NOT NULL REFERENCES public.academic_years(id) ON DELETE RESTRICT,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  grade_id INTEGER REFERENCES public.grades(id) ON DELETE SET NULL,
  section_id INTEGER REFERENCES public.sections(id) ON DELETE SET NULL,
  grade_name VARCHAR(100),
  section_name VARCHAR(100),
  status TEXT NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'completed', 'graduated', 'inactive', 'transferred')),
  source TEXT NOT NULL DEFAULT 'automatic'
    CHECK (source IN ('backfill', 'rollover', 'automatic', 'manual', 'import')),
  started_at DATE NOT NULL DEFAULT current_date,
  ended_at DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (academic_year_id, student_id)
);

CREATE INDEX IF NOT EXISTS student_year_enrollments_student_idx
  ON public.student_academic_year_enrollments (student_id, academic_year_id DESC);
CREATE INDEX IF NOT EXISTS student_year_enrollments_scope_idx
  ON public.student_academic_year_enrollments (academic_year_id, grade_id, section_id, status);

INSERT INTO public.student_academic_year_enrollments (
  academic_year_id, student_id, grade_id, section_id,
  grade_name, section_name, status, source, started_at
)
SELECT
  ss.academic_year_id,
  s.id,
  s.grade_id,
  s.section_id,
  g.name,
  sec.name,
  'active',
  'backfill',
  ay.start_date
FROM public.school_settings ss
JOIN public.academic_years ay ON ay.id = ss.academic_year_id
JOIN public.students s ON s.is_active IS NOT FALSE
LEFT JOIN public.grades g ON g.id = s.grade_id
LEFT JOIN public.sections sec ON sec.id = s.section_id
WHERE ss.id = 1
ON CONFLICT (academic_year_id, student_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.academic_year_rollovers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  idempotency_key UUID NOT NULL UNIQUE,
  from_academic_year_id BIGINT NOT NULL REFERENCES public.academic_years(id) ON DELETE RESTRICT,
  to_academic_year_id BIGINT NOT NULL REFERENCES public.academic_years(id) ON DELETE RESTRICT,
  status TEXT NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'completed', 'reversed', 'failed')),
  promoted_count INTEGER NOT NULL DEFAULT 0,
  graduated_count INTEGER NOT NULL DEFAULT 0,
  unassigned_section_count INTEGER NOT NULL DEFAULT 0,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  reversed_at TIMESTAMPTZ,
  summary JSONB NOT NULL DEFAULT '{}'::JSONB
);

CREATE UNIQUE INDEX IF NOT EXISTS academic_year_rollovers_one_completed_from_idx
  ON public.academic_year_rollovers (from_academic_year_id)
  WHERE status = 'completed';

CREATE TABLE IF NOT EXISTS public.academic_year_rollover_students (
  rollover_id UUID NOT NULL REFERENCES public.academic_year_rollovers(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  previous_grade_id INTEGER REFERENCES public.grades(id) ON DELETE SET NULL,
  previous_section_id INTEGER REFERENCES public.sections(id) ON DELETE SET NULL,
  previous_is_active BOOLEAN NOT NULL,
  previous_is_fingerprint_enrolled BOOLEAN NOT NULL,
  previous_enrolled_at TIMESTAMPTZ,
  action TEXT CHECK (action IN ('promoted', 'graduated')),
  new_grade_id INTEGER REFERENCES public.grades(id) ON DELETE SET NULL,
  new_section_id INTEGER REFERENCES public.sections(id) ON DELETE SET NULL,
  new_is_active BOOLEAN,
  PRIMARY KEY (rollover_id, student_id)
);

